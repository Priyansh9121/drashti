import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { PdfCopyHistory } from './pdf-copy-history';
describe('extracted PDF file Undo', () => {
  it('removes only its own generated file, restores its exact bytes on Redo and refuses a replacement', async () => {
    const parent = join(import.meta.dirname, '../../../test-results/pdf-history');
    await mkdir(parent, { recursive: true });
    const root = await mkdtemp(join(parent, 'placeholder-'));
    try {
      const path = join(root, 'Placeholder.pdf');
      const bytes = Buffer.from('%PDF-1.7\nPlaceholder generated bytes\n%%EOF');
      await writeFile(path, bytes);
      const history = new PdfCopyHistory();
      const id = await history.keep(path);
      expect(await history.show(id, false)).toBe(true);
      await expect(readFile(path)).rejects.toMatchObject({ code: 'ENOENT' });
      await writeFile(path, 'Placeholder unrelated replacement');
      expect(await history.show(id, true)).toBe(false);
      expect(await readFile(path, 'utf8')).toBe('Placeholder unrelated replacement');
      await rm(path);
      expect(await history.show(id, true)).toBe(true);
      expect(await readFile(path)).toEqual(bytes);
      await writeFile(path, 'Placeholder externally changed');
      expect(await history.show(id, false)).toBe(false);
      expect(await readFile(path, 'utf8')).toBe('Placeholder externally changed');
      expect(await history.show('unknown', false)).toBe(false);
    } finally { await rm(root, { recursive: true, force: true }); }
  });
});
