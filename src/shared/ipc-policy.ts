export type IpcPage = keyof typeof PAGE_METHODS;

const methodsByPage = new Map<IpcPage, ReadonlySet<string>>();
const requestsByPage = new Map<IpcPage, ReadonlySet<string>>();
for (const page of Object.keys(PAGE_METHODS) as IpcPage[]) {
  const methods = PAGE_METHODS[page];
  methodsByPage.set(page, new Set(methods));
  requestsByPage.set(page, new Set(methods.flatMap((method) => METHOD_REQUESTS[method] ?? [])));
}

export function bridgeMethodAllowed(page: IpcPage, method: string): boolean {
  return methodsByPage.get(page)?.has(method) ?? false;
}

export function ipcChannelAllowed(page: IpcPage, channel: string): boolean {
  // Appearance is read by the isolated preload before any page draws, including the lock and workers.
  return channel === IPC.appearance.now || (requestsByPage.get(page)?.has(channel) ?? false);
}
