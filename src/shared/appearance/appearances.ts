export interface LookMoving {
  /** What moves, in words (the Appearance window says it). */
  readonly words: string;
  readonly kinds: readonly MotionKind[];
  /**
   * The colour a touch over the header draws in (a drift's far end, a glow, petals, puffs, rain, kites, clouds):
   * the header's words and controls are measured on it as on the header itself (rules.ts), so nothing moving ever
   * takes a word below its contrast.
   */
  readonly touch?: string;
}

export interface Appearance {
  /** "black", "white", … for the built-in ones; "own-…" for one a person made (Session 40). */
  readonly id: string;
  /** Its name, as the menu and the Appearance window show it. */
  readonly name: string;
  readonly base: AppearanceBase;
  readonly colours: Colours;
  readonly decoration: Decoration;
  /** The window's zones (Session 44, zones.ts): the left column, the middle, the right column, the layer bar. */
  readonly zones: Zones;
  /** A built-in one's family (Session 60); one a person makes has none (it is in "Your own"). */
  readonly family?: AppearanceFamily;
  /** A live one's moving touch (Session 60); a still one has none. */
  readonly moving?: LookMoving;
  /**
   * A colourful built-in one's zones as OKLCH hue and chroma (Session 44, zones.ts): its `zones` are zonesOf(its
   * colours, these), written out so a window works nothing out as it opens (contrast.test.ts checks they still are).
   */
  readonly tints?: Tints;
}

/** The family an appearance is shown in. */
export const familyOf = (a: Appearance): AppearanceFamily | typeof OWN_FAMILY => a.family ?? OWN_FAMILY;

/**
 * The decoration of an appearance with no colours of its own there (Black and White): exactly what the window
 * drew before Session 42. The header is a panel, its name in the words' colour and its buttons in the secondary
 * words', with the window's focus ring and controls' edges; the marks are the focus ring's colour; headings are secondary words; and
 * there is no band.
 */
export const plainDecoration = (c: Colours): Decoration => ({
  header: c.panel,
  'on-header': c.fg,
  'on-header-muted': c.muted,
  'header-ring': c.accent,
  'header-field': c.field,
  second: c.accent,
  heading: c.muted,
  'header-2': c.panel,
  strip: c.panel,
  'strip-2': c.panel,
  layer: c['panel-2'],
  'layer-edge': c.line,
  band: [],
});

/** Follow the computer (the default): Black or White, as macOS or Windows is set, changing when it changes. */
export const FOLLOW = 'follow';

/**
 * How the operator window moves (Session 40): Calm (Rising, Session 26g), Lively (more, never on a show
 * control), or Off. Reduced motion on the computer is Off, whatever is chosen.
 */
export type InterfaceMotion = 'calm' | 'lively' | 'off';
export const INTERFACE_MOTIONS: readonly InterfaceMotion[] = ['calm', 'lively', 'off'];

/** What a window draws in now: the appearance shown, its custom properties (vars.ts) and the motion. */
export interface AppearanceNow {
  id: string;
  base: AppearanceBase;
  vars: Readonly<Record<string, string>>;
  motion: InterfaceMotion;
  /** Moving: On or Off (Session 60, the owner's safety rule), as chosen in the Appearance window. */
  moving: boolean;
  /** The shown appearance's moving touch, or none for a still one (Session 60). */
  look: readonly MotionKind[];
  /** This computer has four logical cores or fewer (Session 60, the owner's Q60-45): motion pauses while it streams or records. */
  slow: boolean;
  /**
   * Whether Chromium draws with a graphics chip (Session 60): unknown until its GPU process has said, so a live look
   * never moves before it is known (no chip: it never moves).
   */
  chip: 'unknown' | 'yes' | 'no';
  /**
   * The window's look (alpha.24, the owner's QA24-UI-4): B · Depth while the window follows the computer, the default
   * (styles/look-depth.css: panels on a darker ground, pills, LIVE a red ring and tint); flat, exactly as before, in an
   * appearance chosen by name.
   */
  depth: boolean;
}

/** One a person made (Session 40): kept as its name, base and accent; the rest is worked out (derive.ts). */
export interface OwnAppearance {
  /** "own-" and a random part, made once. */
  id: string;
  name: string;
  base: AppearanceBase;
  /** The next thing to do's colour, "#rrggbb", as chosen. */
  accent: string;
  /**
   * A second colour of one's own (Session 42), "#rrggbb", for what marks and the headings; without one it is
   * worked out from the accent (derive.ts).
   */
  second?: string;
}

