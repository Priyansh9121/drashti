import { expect, test } from '@playwright/test';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import {
  type FlowCell,
  flowScanPage,
  flowTablePage,
  makeFlowPdf,
} from '../../src/main/documents/testing/sabha-flow-pdfs';
import { expectNoSeriousA11yIssues } from './a11y';
import { apiCall, device, networkOn, NETWORK_ENV, pairByQr, pairingCode, pairToken } from './devices';
import { launchApp, operatorPage, operatorReady, type PageGlobals } from './helpers';
import { refusedRequests } from './phone-deck';

/*
 * Sabha flow on a paired phone (alpha.23, QA23-FLOW-1 and QA23-FLOW-2): on the Show tab (QA23-PHONE-1; in More until
 * then), the running order the operator chose on the computer, read only: Now and, larger, Next up as the operator marks them;
 * Open Sabha flow… shows the read list (each item as "1 · Program · Details · Duration · Presenter", a merged cell on
 * each row it covers, the total at the bottom, the PDF's own language as its lang) and the PDF page, zoomed from the
 * screen's width. It follows the computer: another PDF chosen starts it again, a scan shows its page alone with plain
 * words, and once removed it says there is none. In Simple Mode on the computer it is there too, whatever Simple Mode
 * Features has (the owner's Q3, "Always"). A Stage device cannot read it. Placeholder PDFs the test makes itself
 * (placeholder words only), generated by the reader's own maker.
 */

const HEADERS = ['No.', 'Program', 'Details', 'Duration', 'Presenter'];
const WIDTHS = [40, 140, 180, 80, 115];

/** An English running order: three items, the last two sharing one Duration and Presenter (a merged cell). */
const ENGLISH: FlowCell[][] = [
  ['1', 'Placeholder opening', 'Placeholder words of welcome', '5 min', 'Placeholder A'],
  [
    '2',
    'Video',
    'Placeholder clip of the week',
    { text: '20 min', rows: 2 },
    { text: 'Placeholder B', rows: 2 },
  ],
  ['3', 'Placeholder talk', 'Placeholder topic', null, null],
];

/** Gujarati placeholder words ("sample", "sample programme", "sample words"), never anything real. */
const GUJARATI: FlowCell[][] = [
  ['1', 'નમૂના કાર્યક્રમ', 'નમૂના શબ્દો', '૫ મિનિટ', 'નમૂના'],
  ['2', 'નમૂના વાત', 'નમૂના વિષય', '૧૦ મિનિટ', 'નમૂના'],
];

async function pdfFile(dir: string, name: string, bytes: Promise<Uint8Array>): Promise<string> {
  const file = join(dir, name);
  writeFileSync(file, await bytes);
  return file;
}

/** "Choose PDF…" in the operator window, the system's dialog answered by the test with this file. */
async function choose(app: ElectronApplication, win: Page, file: string): Promise<string> {
  await app.evaluate(({ dialog }, path) => {
    dialog.showOpenDialog = () => Promise.resolve({ canceled: false, filePaths: [path] });
  }, file);
  return win.evaluate(async () => {
    const chosen = await (globalThis as PageGlobals).drashti.flow.choose();
    if (!chosen?.ok) throw new Error(chosen ? chosen.message : 'The Sabha flow was not chosen');
    return chosen.flow.id;
  });
}

/** What a line shows, without what only a screen reader hears (the comma read in place of each middle dot). */
const shown = (l: Locator) =>
  l.evaluate((el) => {
    const copy = el.cloneNode(true) as Element;
    for (const n of copy.querySelectorAll('.sr-only')) n.remove();
    return copy.textContent.replace(/\s+/gu, ' ').trim();
  });

const markNow = (win: Page, flowId: string, now: number | null) =>
  win.evaluate(
    async ({ flowId, now }) => {
      const done = await (globalThis as PageGlobals).drashti.flow.setNow(flowId, now);
      if (!done.ok) throw new Error(done.message);
    },
    { flowId, now },
  );

test('Sabha flow on a paired phone: Now and Next up, the read list and the PDF page, read only, following the computer’s PDF as it is chosen, marked, replaced and removed', async () => {
  test.setTimeout(240_000);
  const { app } = await launchApp(NETWORK_ENV);
  const win = await operatorPage(app);
  await operatorReady(win);
  const dir = mkdtempSync(join(tmpdir(), 'drashti-remote-flow-'));
  const english = await pdfFile(
    dir,
    'Placeholder evening order.pdf',
    makeFlowPdf([
      flowTablePage({
        title: 'Placeholder Evening Sabha',
        subtitle: 'Placeholder hall, placeholder date',
        headers: HEADERS,
        rows: ENGLISH,
        widths: WIDTHS,
        total: 'Placeholder total: 30 min',
      }),
      flowScanPage(),
    ]),
  );
  const gujarati = await pdfFile(
    dir,
    'Placeholder Gujarati order.pdf',
    makeFlowPdf([flowTablePage({ title: 'નમૂના સભા', headers: HEADERS, rows: GUJARATI, widths: WIDTHS })]),
  );
  const scan = await pdfFile(dir, 'Placeholder scanned order.pdf', makeFlowPdf([flowScanPage()]));
  const { base, port } = await networkOn(win);
  const code = await pairingCode(win, 'remote', 'Placeholder phone');
  const phone = await device('chromium');
  const p = phone.page;
  const refused = refusedRequests(p);
  try {
    await p.setViewportSize({ width: 390, height: 844 });
    await pairByQr(p, base, code, '/remote');
    await expect(p.getByTestId('connection')).toHaveText('Connected');
    await p.getByTestId('remote-tab-show').click();
    const section = p.getByTestId('remote-flow');
    // None yet: plain words, and nothing to open.
    await expect(section.getByTestId('remote-flow-none')).toContainText('There is no Sabha flow yet');
    await expect(section.getByTestId('remote-open-flow')).toHaveCount(0);

    // Chosen on the computer: the phone follows at once (the feed's hint), Now not started and Next up the first.
    const first = await choose(app, win, english);
    await expect(section.getByTestId('remote-flow-file')).toHaveText('Placeholder evening order.pdf');
    await expect(section.getByTestId('remote-flow-now')).toHaveText('Now: not started');
    await expect
      .poll(() => shown(section.getByTestId('remote-flow-next')))
      .toBe('Next up: 1 · Placeholder opening · Placeholder words of welcome · 5 min · Placeholder A');

    // Marked on the computer: Now the first, Next up the video row, its merged cells as its own, marked as a video.
    await markNow(win, first, 0);
    await expect
      .poll(() => shown(section.getByTestId('remote-flow-now')))
      .toBe('Now: 1 · Placeholder opening · Placeholder words of welcome');
    const next = section.getByTestId('remote-flow-next');
    await expect
      .poll(() => shown(next))
      .toBe('Next up: 2 · Video · Placeholder clip of the week · 20 min · Placeholder B');
    await expect(next).toHaveAttribute('data-video', 'true');

    // The sheet: the read list, Now and Next up marked, the merged cells on both rows, the total, in English.
    await section.getByTestId('remote-open-flow').click();
    const sheet = p.getByTestId('remote-flow-sheet');
    await expect(sheet).toBeVisible();
    await expect(sheet.getByTestId('remote-flow-view-list')).toHaveAttribute('aria-selected', 'true');
    const rows = sheet.getByTestId('remote-flow-row');
    await expect(rows).toHaveCount(3);
    await expect(rows.nth(0)).toHaveAttribute('aria-current', 'step');
    await expect(rows.nth(1)).toHaveAttribute('data-next', 'true');
    expect(await shown(rows.nth(2))).toBe(
      '3 · Placeholder talk · Placeholder topic · 20 min · Placeholder B',
    );
    await expect(rows.nth(2).locator('[lang="en"]', { hasText: 'Placeholder talk' })).toHaveCount(1);
    await expect(sheet.getByTestId('remote-flow-total')).toHaveText('Placeholder total: 30 min');
    await expectNoSeriousA11yIssues(
      p,
      'the Sabha flow’s read list on a phone',
      '[data-testid="remote-flow-sheet"]',
    );

    // Now moved on the computer while the sheet is open: it follows, read only (a row is not a button).
    await markNow(win, first, 2);
    await expect(rows.nth(2)).toHaveAttribute('aria-current', 'step');
    await expect(sheet.getByTestId('remote-flow-next')).toHaveText('Last item');
    await expect(rows.nth(0).locator('button')).toHaveCount(0);

    // The PDF page: its picture as the computer drew it, its second page, zoomed and back to the screen's width.
    await sheet.getByTestId('remote-flow-view-page').click();
    const picture = sheet.getByTestId('remote-flow-picture');
    const drawn = () =>
      picture.evaluate((img) => img instanceof HTMLImageElement && img.complete && img.naturalWidth > 0);
    await expect.poll(drawn).toBe(true);
    await expect(sheet.getByTestId('remote-flow-page-number')).toHaveText('Page 1 of 2');
    await sheet.getByTestId('remote-flow-next-page').click();
    await expect(sheet.getByTestId('remote-flow-page-number')).toHaveText('Page 2 of 2');
    await expect.poll(drawn).toBe(true);
    const box = sheet.getByTestId('remote-flow-page-box');
    const fit = await picture.evaluate((img) => img.getBoundingClientRect().width);
    await sheet.getByTestId('remote-flow-zoom-in').click();
    await expect(box).toHaveAttribute('data-zoom', '1.5');
    expect(await picture.evaluate((img) => img.getBoundingClientRect().width)).toBeCloseTo(fit * 1.5, 0);
    await sheet.getByTestId('remote-flow-zoom-fit').click();
    await expect(box).toHaveAttribute('data-zoom', '1');
    await expectNoSeriousA11yIssues(
      p,
      'the Sabha flow’s PDF page on a phone',
      '[data-testid="remote-flow-sheet"]',
    );

    // Replaced on the computer by a Gujarati one: the sheet starts again on its read list, in Gujarati (lang gu).
    await choose(app, win, gujarati);
    await expect(sheet.getByTestId('remote-flow-sheet-file')).toHaveText('Placeholder Gujarati order.pdf');
    await expect(sheet.getByTestId('remote-flow-view-list')).toHaveAttribute('aria-selected', 'true');
    await expect(rows).toHaveCount(2);
    await expect(rows.nth(0).locator('[lang="gu"]', { hasText: 'નમૂના કાર્યક્રમ' })).toHaveCount(1);
    await expect(sheet.getByTestId('remote-flow-now')).toHaveText('Now: not started');

    // A scan: plain words, and its page alone.
    await choose(app, win, scan);
    await expect(sheet.getByTestId('remote-flow-status')).toContainText('no words Drashti can read');
    await expect(sheet.getByTestId('remote-flow-view-list')).toHaveCount(0);
    await expect.poll(drawn).toBe(true);
    await expect(sheet.getByTestId('remote-flow-page-number')).toHaveCount(0);

    // Removed on the computer: the sheet and the Show tab say there is none.
    await win.evaluate(() => (globalThis as PageGlobals).drashti.flow.remove());
    await expect(sheet.getByTestId('remote-flow-sheet-none')).toContainText('There is no Sabha flow yet');
    await sheet.getByTestId('remote-flow-sheet-close').click();
    await expect(sheet).toHaveCount(0);
    await expect(section.getByTestId('remote-flow-none')).toBeVisible();

    // Never a Stage device's: it is never on a screen.
    const stage = await pairToken(win, port, 'stage', 'Placeholder stage tablet');
    expect((await apiCall(port, '/api/v1/flow', { token: stage })).status).toBe(403);

    // Last (Simple Mode pairs nothing): Simple Mode on the computer, Sabha flow not among Simple Mode Features: the
    // phone shows the flow all the same (the owner's Q3, "Always"), and its sheet.
    await choose(app, win, english);
    await win.evaluate(() => (globalThis as PageGlobals).drashti.app.setMode('simple'));
    await expect(p.getByTestId('remote-simple')).toBeVisible();
    await expect(section.getByTestId('remote-flow-file')).toHaveText('Placeholder evening order.pdf');
    await section.getByTestId('remote-open-flow').click();
    await expect(sheet.getByTestId('remote-flow-row')).toHaveCount(3);
    await sheet.getByTestId('remote-flow-sheet-close').click();
    await expect(sheet).toHaveCount(0);
    expect(refused, 'requests Drashti refused this phone').toEqual([]);
  } finally {
    await phone.close();
    await app.close();
  }
});
